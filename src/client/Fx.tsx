const BASE = ((import.meta as unknown as { env?: { BASE_URL?: string } }).env?.BASE_URL ?? '/').replace(/\/?$/, '/');
export const reducedMotion = () => typeof matchMedia !== 'undefined' && matchMedia('(prefers-reduced-motion: reduce)').matches;

// ---------------------------------------------------------------- sound (CC0, generated by scripts/gen-sfx.py)
export type Sfx = 'dice' | 'card' | 'attack' | 'haunt' | 'ping';
const MUTE_KEY = 'betrayal-mute';
let muted = (() => { try { return localStorage.getItem(MUTE_KEY) === '1'; } catch { return false; } })();
const listeners = new Set<() => void>();
const cache: Partial<Record<Sfx, HTMLAudioElement>> = {};
export function sfx(name: Sfx) {
  if (muted || typeof Audio === 'undefined') return;
  try {
    const a = (cache[name] ??= new Audio(`${BASE}sfx/${name}.wav`)); const b = a.cloneNode() as HTMLAudioElement;
    b.volume = name === 'haunt' ? 0.7 : 0.45; void b.play().catch(() => { /* autoplay blocked until the first click */ });
  } catch { /* no audio */ }
}
export function MuteToggle() {
  const [m, setM] = useState(muted);
  useEffect(() => { const f = () => setM(muted); listeners.add(f); return () => { listeners.delete(f); }; }, []);
  return <button className="small ghostbtn mute" title={m ? 'Bật âm thanh' : 'Tắt âm thanh'} aria-label={m ? 'Bật âm thanh' : 'Tắt âm thanh'}
    onClick={() => { muted = !muted; try { localStorage.setItem(MUTE_KEY, muted ? '1' : '0'); } catch { /* ignore */ } listeners.forEach((f) => f()); if (!muted) sfx('ping'); }}>{m ? '🔇' : '🔊'}</button>;
}

// ---------------------------------------------------------------- dice
type Rolls = NonNullable<GState['lastRolls']>;
function outcomeLines(G: GState, r: Rolls) {
  return G.log.filter((l) => (l.s ?? -1) > r.logFrom && (l.s ?? -1) <= r.logTo && !l.text.startsWith('—')).map((l) => l.text).slice(0, 5);
}
/** Big dice overlay shown to every client after a roll: faces, why that many dice, total, outcome. */
export function DiceOverlay({ G, who }: { G: GState; who: (pid: string) => string }) {
  const r = G.lastRolls; const seq = r?.seq ?? 0;
  const [shown, setShown] = useState<{ seq: number; phase: 'roll' | 'land' } | null>(null);
  const first = useRef(true);
  useEffect(() => {
    if (first.current) { first.current = false; return; } // only rolls that happen while we watch
    if (!r) return;
    const rm = reducedMotion();
    setShown({ seq, phase: rm ? 'land' : 'roll' }); sfx(r.items.some((i) => /tấn công/i.test(i.label)) ? 'attack' : 'dice');
    const t1 = setTimeout(() => setShown((s) => (s?.seq === seq ? { seq, phase: 'land' } : s)), rm ? 0 : 750);
    const t2 = setTimeout(() => setShown((s) => (s?.seq === seq ? null : s)), 3400);
    return () => { clearTimeout(t1); clearTimeout(t2); };
  }, [seq]);
  if (!r || !shown || shown.seq !== seq) return null;
  const land = shown.phase === 'land'; const lines = outcomeLines(G, r);
  return (
    <div className={`diceov ${shown.phase}`} role="status" aria-live="polite">
      <div className="do-card" onClick={() => setShown(null)} title="Bấm để đóng">
        <div className="do-title">🎲 Đổ xúc xắc</div>
        {r.items.slice(0, 6).map((it, k) => (
          <div key={k} className="do-row">
            <div className="do-head"><b>{who(it.who)}</b> · {it.label}</div>
            {it.reason && <div className="do-why">{it.reason}</div>}
            <div className="do-dice">{(it.dice.length ? it.dice : []).map((d, i) => <Die key={`${seq}-${k}-${i}`} value={land ? d : (i + k + 1) % 3} rolling={!land} delay={i * 45} />)}
              {!it.dice.length && <span className="muted small">0 xúc xắc</span>}
              <span className="do-total">{land ? <>= <b>{it.total}</b></> : '…'}</span></div>
          </div>))}
        {r.items.length > 6 && <div className="muted small">… và {r.items.length - 6} lần đổ nữa (xem nhật ký)</div>}
        {land && lines.length > 0 && <div className="do-out">{lines.map((l, i) => <div key={i}>{l}</div>)}</div>}
        <div className="do-hint">Mặt xúc xắc Betrayal: 0, 1 hoặc 2 chấm · bấm để đóng</div>
      </div>
    </div>);
}
/** Compact "Lần đổ gần nhất" panel (side bar). */
export function LastRollPanel({ G, who }: { G: GState; who: (pid: string) => string }) {
  const r = G.lastRolls; if (!r) return null; const lines = outcomeLines(G, r);
  return (
    <div className="panel lastroll">
      <h3>🎲 Lần đổ gần nhất</h3>
      {r.items.slice(0, 4).map((it, k) => <div key={k} className="lr-row"><div className="small"><b>{who(it.who)}</b> · {it.label}{it.reason ? <span className="muted"> — {it.reason}</span> : null}</div>
        <div className="lr-dice">{it.dice.map((d, i) => <Die key={i} value={d} />)}<span>= <b>{it.total}</b></span></div></div>)}
      {lines.length > 0 && <div className="small muted lr-out">{lines.slice(-2).join(' · ')}</div>}
    </div>);
}
/** The big roll button (only for the player who must roll). */
export function RollButton({ label, reason, onRoll }: { label: string; reason?: string; onRoll: () => void }) {
  useEffect(() => { sfx('ping'); }, [label]);
  return (
    <div className="panel pending rollpanel">
      <div className="rp-what">{label}</div>
      {reason && <div className="rp-why">{reason}</div>}
      <button className="rollbtn" onClick={onRoll} autoFocus>🎲 Đổ xúc xắc</button>
      <div className="small muted">Xúc xắc được đổ trên server khi bạn bấm — mọi người cùng thấy kết quả.</div>
    </div>);
}

