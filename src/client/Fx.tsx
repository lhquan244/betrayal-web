/** A drawn card flies from its pile, flips face up and zooms to the centre. The drawer presses "Tiếp tục"; others auto-continue. */
export function CardDraw({ id, G, drawer, isDrawer, auto, onClose }: { id: string; G: GState; drawer: string; isDrawer: boolean; auto?: number; onClose: () => void }) {
  const def = CARD_BY_ID[id]; const ref = useRef<HTMLDivElement>(null);
  const [stage, setStage] = useState<'from' | 'fly' | 'flip' | 'open'>(reducedMotion() ? 'open' : 'from');
  const [from, setFrom] = useState<{ x: number; y: number }>({ x: 0, y: -260 });
  const room = G.players[drawer]?.room;
  useLayoutEffect(() => {
    if (stage !== 'from') return;
    const pile = document.querySelector(`[data-pile="${def?.kind}"]`) as HTMLElement | null;
    if (pile) { const b = pile.getBoundingClientRect(); setFrom({ x: b.left + b.width / 2 - innerWidth / 2, y: b.top + b.height / 2 - innerHeight / 2 }); }
    sfx('card');
    const t0 = requestAnimationFrame(() => requestAnimationFrame(() => setStage('fly')));
    const t1 = setTimeout(() => setStage('flip'), 650); const t2 = setTimeout(() => setStage('open'), 1150);
    return () => { cancelAnimationFrame(t0); clearTimeout(t1); clearTimeout(t2); };
  }, []);
  useEffect(() => { if (!isDrawer || auto) { const t = setTimeout(onClose, auto ?? 4500); return () => clearTimeout(t); } }, [isDrawer, auto]);
  if (!def) return null; const Icon = KIND_ICON[def.kind];
  const tf = stage === 'from' ? `translate(${from.x}px, ${from.y}px) scale(.22) rotateY(180deg)` : stage === 'fly' ? 'translate(0,0) scale(.8) rotateY(180deg)' : 'translate(0,0) scale(1) rotateY(0deg)';
  return (
    <div className={`modal carddraw st-${stage}`} onClick={() => { if (stage === 'open') onClose(); else setStage('open'); }} title="Bấm để xem ngay">
      {room && <div className="cd-room">Khám phá <b>{roomName(room)}</b> → rút lá <b>{KIND_VI[def.kind]}</b></div>}
      <div ref={ref} className="cd-flip" style={{ transform: tf }} onClick={(e) => e.stopPropagation()}>
        <div className={`cd-back ${def.kind}`}><Icon size={70} /><span>{KIND_VI[def.kind]}</span></div>
        <div className={`gcard ${def.kind} cd-front`}>
          <div className="gcard-inner">
            <div className="gcard-kind">{KIND_VI[def.kind]}</div>
            <div className="gcard-icon"><Icon size={54} /></div>
            <h2>{def.name}</h2>
            <div className="gcard-rule" />
            <p>{def.text}</p>
            {def.todo && <p className="todo">⚠ Chưa tự động: {def.todo} — dùng “Điều chỉnh thủ công”.</p>}
            <button className="primary" onClick={onClose}>{isDrawer ? 'Tiếp tục ➜' : 'Đóng'}</button>
          </div>
        </div>
      </div>
    </div>);
}

// ---------------------------------------------------------------- floating trait changes
/** "+1" / "−2" that floats up next to a trait when its value changes. */
export function useTraitFloats(key: string, values: Record<string, number>) {
  const prev = useRef<Record<string, number> | null>(null);
  const [floats, setFloats] = useState<{ id: number; trait: string; d: number }[]>([]);
  const sig = JSON.stringify(values);
  useEffect(() => {
    const p = prev.current; prev.current = values; if (!p) return;
    const add = Object.keys(values).filter((t) => values[t] !== p[t]).map((t, i) => ({ id: Date.now() + i, trait: t, d: values[t] - p[t] }));
    if (!add.length) return;
    setFloats((f) => [...f, ...add]);
    setTimeout(() => setFloats((f) => f.filter((x) => !add.includes(x))), 1500);
  }, [key, sig]);
  return floats;
}
